"""Generate aml_gnn_adapter.py: ONE self-contained file holding graph_builder +
model + model_adapter, because Foundry packages only the adapter's own .py
file with a published model (sibling imports are not bundled). Run after any
change to those three files:

    python build_adapter_bundle.py

graph_builder.py / model.py / model_adapter.py stay the source of truth for
training; the bundle is what gets PUBLISHED (publish_checkpoint.py and
train_gnn_foundry.py load the checkpoint into the bundle's adapter class).
"""
import hashlib
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCES = ["graph_builder.py", "model.py", "model_adapter.py"]
OUT = os.path.join(HERE, "aml_gnn_adapter.py")
LOCAL_IMPORT = re.compile(r"^from (graph_builder|model) import .*$", re.M)


def build() -> str:
    parts, digest = [], hashlib.sha256()
    for name in SOURCES:
        src = open(os.path.join(HERE, name)).read()
        digest.update(src.encode())
        src = LOCAL_IMPORT.sub(lambda m: f"# (inlined) {m.group(0)}", src)
        src = src.replace("from __future__ import annotations\n", "")
        parts.append(f"# {'=' * 70}\n# >>> {name}\n# {'=' * 70}\n{src}")
    header = (
        '"""AUTO-GENERATED by build_adapter_bundle.py -- DO NOT EDIT.\n'
        "Self-contained AML GNN model adapter (graph_builder + model + adapter)\n"
        "so the published model has no sibling-module imports.\n"
        f'sources-sha256: {digest.hexdigest()}\n"""\n'
        "from __future__ import annotations\n"
    )
    return header + "\n".join(parts)


if __name__ == "__main__":
    text = build()
    open(OUT, "w").write(text)
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
